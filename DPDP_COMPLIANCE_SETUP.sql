-- DPDP Compliance Setup for QuickOHunt
-- Document Retention & Verification Consent Tables

-- Table 1: Verification Consent Records
create table if not exists public.verification_consent (
  id bigint generated by default as identity primary key,
  user_id text not null,
  consent_given boolean not null default false,
  consent_given_at timestamp with time zone,
  retention_days integer not null default 30,
  verification_method text not null check (verification_method in ('local', 'backend')),
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  
  constraint verification_consent_user_id_fkey 
    foreign key (user_id) references auth.users(id) on delete cascade,
  constraint verification_consent_user_id_unique unique (user_id)
);

-- Table 2: Document Retention Schedule
create table if not exists public.document_retention (
  id bigint generated by default as identity primary key,
  user_id text not null,
  document_type text not null check (document_type in ('id', 'selfie', 'address_proof', 'pan', 'aadhar')),
  storage_path text,
  uploaded_at timestamp with time zone not null default now(),
  delete_at timestamp with time zone not null,
  deleted boolean not null default false,
  deleted_at timestamp with time zone,
  created_at timestamp with time zone not null default now(),
  
  constraint document_retention_user_id_fkey 
    foreign key (user_id) references auth.users(id) on delete cascade
);

-- Table 3: Verification Status (No personal data)
create table if not exists public.verification_status (
  id bigint generated by default as identity primary key,
  user_id text not null,
  identity_verified boolean not null default false,
  identity_verified_at timestamp with time zone,
  identity_verification_method text check (identity_verification_method in ('ai_assisted', 'manual', 'local')),
  profile_verified boolean not null default false,
  profile_verified_at timestamp with time zone,
  vehicle_verified boolean not null default false,
  vehicle_verified_at timestamp with time zone,
  overall_verified boolean not null default false,
  overall_verified_at timestamp with time zone,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  
  constraint verification_status_user_id_fkey 
    foreign key (user_id) references auth.users(id) on delete cascade,
  constraint verification_status_user_id_unique unique (user_id)
);

-- Table 4: Audit Log (for compliance tracking)
create table if not exists public.data_audit_log (
  id bigint generated by default as identity primary key,
  user_id text not null,
  action text not null,
  data_type text not null,
  description text,
  performed_by text, -- 'user', 'system', 'admin'
  created_at timestamp with time zone not null default now(),
  
  constraint data_audit_log_user_id_fkey 
    foreign key (user_id) references auth.users(id) on delete cascade
);

-- Create indexes for performance
create index if not exists idx_verification_consent_user_id 
  on public.verification_consent(user_id);

create index if not exists idx_document_retention_delete_at 
  on public.document_retention(delete_at, deleted);

create index if not exists idx_document_retention_user_id 
  on public.document_retention(user_id);

create index if not exists idx_verification_status_user_id 
  on public.verification_status(user_id);

create index if not exists idx_data_audit_log_user_id 
  on public.data_audit_log(user_id, created_at);

-- Enable RLS on all tables
alter table public.verification_consent enable row level security;
alter table public.document_retention enable row level security;
alter table public.verification_status enable row level security;
alter table public.data_audit_log enable row level security;

-- RLS Policies for verification_consent
create policy "Users can view their own consent" 
  on public.verification_consent for select 
  using (auth.uid()::text = user_id);

create policy "Users can insert their own consent" 
  on public.verification_consent for insert 
  with check (auth.uid()::text = user_id);

create policy "Users can update their own consent" 
  on public.verification_consent for update 
  using (auth.uid()::text = user_id);

-- RLS Policies for document_retention
create policy "Users can view their own document retention" 
  on public.document_retention for select 
  using (auth.uid()::text = user_id);

create policy "Users can insert their own document retention" 
  on public.document_retention for insert 
  with check (auth.uid()::text = user_id);

-- RLS Policies for verification_status
create policy "Users can view their own verification status" 
  on public.verification_status for select 
  using (auth.uid()::text = user_id);

create policy "System can update verification status" 
  on public.verification_status for update 
  using (true); -- Use service role for updates

-- RLS Policies for data_audit_log
create policy "Users can view their own audit log" 
  on public.data_audit_log for select 
  using (auth.uid()::text = user_id);

-- Function: Auto-update updated_at timestamp
create or replace function update_updated_at_column()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

-- Triggers for updated_at
create trigger verification_consent_updated_at_trigger
  before update on public.verification_consent
  for each row
  execute function update_updated_at_column();

create trigger verification_status_updated_at_trigger
  before update on public.verification_status
  for each row
  execute function update_updated_at_column();

-- Grant permissions
grant select, insert, update on public.verification_consent to authenticated;
grant select, insert on public.document_retention to authenticated;
grant select on public.verification_status to authenticated;
grant insert on public.data_audit_log to authenticated;
